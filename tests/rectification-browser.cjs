const assert = require('node:assert/strict')
const path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')

async function main() {
  const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_EXECUTABLE ? { executablePath: process.env.PLAYWRIGHT_EXECUTABLE } : {}) })
  const errors = []
  const contexts = []
  const open = async (role, mobile = false) => {
    const context = await browser.newContext({ viewport: mobile ? { width: 390, height: 844 } : { width: 1440, height: 1000 } })
    contexts.push(context)
    const page = await context.newPage()
    page.on('pageerror', (error) => errors.push(error.message))
    await page.route(/^http:\/\/127\.0\.0\.1:5174\/api\//, async (route) => {
      const request = route.request()
      const url = new URL(request.url())
      const response = await route.fetch({ url: `http://127.0.0.1:8001${url.pathname}${url.search}` })
      await route.fulfill({ response })
    })
    await page.goto('http://127.0.0.1:5174/')
    await page.getByRole('button', { name: '进入管理平台', exact: true }).first().click()
    await page.getByLabel('账号', { exact: true }).fill(`preview-${role}`)
    await page.getByLabel('密码', { exact: true }).fill('preview123456')
    await page.getByRole('button', { name: '登录并进入平台' }).click()
    if (mobile) await page.getByRole('button', { name: '打开导航', exact: true }).click()
    await page.locator('.main-nav').getByRole('button', { name: /^整改闭环/ }).click()
    await page.locator('.rect-group-title').first().click()
    await page.getByRole('button', { name: '查看并处理', exact: true }).first().click()
    await page.getByRole('dialog', { name: '整改任务详情' }).waitFor()
    return page
  }
  const note = (page, text) => page.getByRole('textbox', { name: '进展说明', exact: true }).fill(text)
  const waitLog = async (page, text) => page.locator('.rectification-timeline').getByText(text, { exact: true }).waitFor()
  const save = async (page, text, button) => {
    await note(page, text)
    await page.getByRole('button', { name: button, exact: true }).click()
    await waitLog(page, text)
  }
  const evidence = async (page) => {
    await page.getByRole('textbox', { name: '复核检测值', exact: true }).fill('8')
    await page.getByLabel('上传整改照片', { exact: true }).setInputFiles(path.join(__dirname, '../public/reference-product.png'))
    await page.locator('.rectification-photo').first().waitFor()
    await page.getByRole('checkbox').check()
  }
  try {
    const manager = await open('project_manager')
    await save(manager, '已设置隔离并通知责任班组', '保存处理记录')
    assert.equal(await manager.locator('.detail-grid').getByText('整改中', { exact: true }).count(), 1)
    assert.equal(await manager.getByRole('textbox', { name: '进展说明', exact: true }).inputValue(), '已设置隔离并通知责任班组')
    assert.equal(await manager.getByRole('button', { name: '保存并提交原安全员', exact: true }).isEnabled(), true)
    await manager.getByRole('button', { name: '修改', exact: true }).click()
    await note(manager, '取消后的草稿不应保存')
    await manager.getByRole('button', { name: '取消修改', exact: true }).click()
    assert.equal(await manager.getByRole('textbox', { name: '进展说明', exact: true }).inputValue(), '已设置隔离并通知责任班组')
    await manager.getByRole('button', { name: '修改', exact: true }).click()
    assert.equal(await manager.getByRole('button', { name: '保存并提交原安全员', exact: true }).count(), 0)
    await save(manager, '已设置隔离并复查责任班组', '保存修改')
    await waitLog(manager, '已设置隔离并通知责任班组')
    assert.equal(await manager.locator('.detail-grid').getByText('整改中', { exact: true }).count(), 1)
    assert.equal(await manager.getByRole('button', { name: '保存并提交原安全员', exact: true }).isEnabled(), true)
    assert.equal(await manager.getByRole('button', { name: '修改', exact: true }).count(), 1)
    await note(manager, '误触阶段，撤回核对')
    await manager.getByRole('button', { name: '撤回至待整改', exact: true }).click()
    await waitLog(manager, '误触阶段，撤回核对')
    await save(manager, '重新开始整改', '保存并开始整改')
    await manager.getByLabel('上传整改照片', { exact: true }).setInputFiles(path.join(__dirname, '../public/reference-product.png'))
    await manager.locator('.rectification-photo').first().waitFor()
    await save(manager, '设备维修完毕，请原安全员复核', '保存处理记录')
    assert.equal(await manager.locator('.detail-grid').getByText('整改中', { exact: true }).count(), 1)
    assert.equal(await manager.getByRole('textbox', { name: '进展说明', exact: true }).inputValue(), '设备维修完毕，请原安全员复核')
    assert.equal(await manager.getByRole('button', { name: '保存并提交原安全员', exact: true }).isEnabled(), true)
    await manager.getByRole('button', { name: '保存并提交原安全员', exact: true }).click()
    await manager.locator('.detail-grid').getByText('待复核', { exact: true }).waitFor()
    assert.equal(await manager.locator('.rectification-timeline img').count(), 2)
    assert.equal(await manager.getByRole('button', { name: '保存并开始复核' }).count(), 0)

    const reviewer = await open('safety_manager', true)
    await save(reviewer, '原安全员到场开展复核', '保存并开始复核')
    await note(reviewer, '复核初步检查')
    await reviewer.getByRole('button', { name: '复核合格并交回项目经理' }).click()
    await reviewer.getByRole('alert').getByText(/填写复核检测值/).waitFor()
    await evidence(reviewer)
    await reviewer.getByRole('textbox', { name: '复核检测值' }).fill('18')
    await reviewer.getByRole('checkbox').check()
    await reviewer.getByRole('button', { name: '复核合格并交回项目经理' }).click()
    await reviewer.getByRole('alert').getByText(/未达到控制标准/).waitFor()
    await reviewer.getByRole('textbox', { name: '复核检测值' }).fill('8')
    await reviewer.getByRole('checkbox').check()
    await save(reviewer, '检测值为8，照片已上传，已核对标准', '保存处理记录')
    await reviewer.screenshot({ path: 'logs/rectification-mobile.png', fullPage: true })
    const mobileFits = await reviewer.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)
    assert.equal(mobileFits, true)
    assert.equal(await reviewer.getByRole('textbox', { name: '进展说明', exact: true }).inputValue(), '检测值为8，照片已上传，已核对标准')
    assert.equal(await reviewer.getByRole('textbox', { name: '复核检测值', exact: true }).inputValue(), '8')
    assert.equal(await reviewer.getByRole('checkbox').isChecked(), true)
    await reviewer.getByRole('button', { name: '修改', exact: true }).click()
    await reviewer.getByRole('textbox', { name: '复核检测值', exact: true }).fill('7')
    await reviewer.getByRole('checkbox').check()
    await save(reviewer, '更正检测值为7，现场照片不变', '保存修改')
    assert.equal(await reviewer.locator('.detail-grid').getByText('复核中', { exact: true }).count(), 1)
    assert.equal(await reviewer.getByRole('textbox', { name: '复核检测值', exact: true }).inputValue(), '7')
    await reviewer.screenshot({ path: 'logs/rectification-edit-mobile.png', fullPage: true })
    assert.equal(await reviewer.getByRole('button', { name: '复核合格并交回项目经理' }).isEnabled(), true)
    await reviewer.getByRole('button', { name: '复核合格并交回项目经理' }).click()
    await reviewer.locator('.detail-grid').getByText('待项目经理确认', { exact: true }).waitFor()
    assert.equal(await reviewer.getByRole('button', { name: '修改', exact: true }).count(), 0)
    await reviewer.getByRole('textbox', { name: '撤回原因' }).fill('复核误触提交，重新确认照片')
    await reviewer.getByRole('button', { name: '撤回至复核中', exact: true }).click()
    await waitLog(reviewer, '复核误触提交，重新确认照片')
    await evidence(reviewer)
    await save(reviewer, '重新核对检测与照片，复核通过', '复核合格并交回项目经理')

    await manager.getByRole('button', { name: '关闭', exact: true }).click()
    await manager.getByRole('button', { name: '刷新记录', exact: true }).click()
    await manager.getByRole('button', { name: '查看并处理', exact: true }).first().click()
    await manager.locator('.detail-grid').getByText('待项目经理确认', { exact: true }).waitFor()
    await manager.screenshot({ path: 'logs/rectification-desktop.png', fullPage: true })
    await save(manager, '已核对安全员检测数据与证据，确认闭环', '确认完成闭环')
    await manager.getByRole('button', { name: '关闭', exact: true }).click()
    const metricValue = async (label) => manager.locator('.metric-card').filter({ has: manager.locator('.metric-top > span').getByText(label, { exact: true }) }).locator('.metric-value').innerText()
    assert.match(await metricValue('隐患总数'), /^0/)
    assert.match(await metricValue('已闭环问题'), /^1/)
    assert.equal(await manager.locator('.rect-item').count(), 0)
    await manager.getByText('当前没有待处理隐患', { exact: true }).waitFor()
    await manager.screenshot({ path: 'logs/rectification-closed-hidden.png', fullPage: true })
    await manager.locator('.main-nav').getByRole('button', { name: '安全驾驶舱', exact: true }).click()
    assert.match(await metricValue('重大 / 较大风险'), /^0/)
    assert.equal(await manager.locator('.priority-row').count(), 0)
    assert.match(await metricValue('整改闭环率'), /^100/)
    await manager.reload()
    await manager.getByRole('button', { name: '进入管理平台', exact: true }).first().click()
    await manager.locator('.main-nav').getByRole('button', { name: /^整改闭环/ }).click()
    assert.equal(await manager.locator('.rect-item').count(), 0)
    await manager.getByRole('tab', { name: /已闭环记录/ }).click()
    await manager.locator('.rect-group-title').first().click()
    await manager.getByRole('button', { name: '查看', exact: true }).first().click()
    await waitLog(manager, '已核对安全员检测数据与证据，确认闭环')
    await manager.locator('.detail-grid').getByText('已闭环', { exact: true }).waitFor()
    assert.equal(await manager.getByRole('button', { name: '修改', exact: true }).count(), 0)
    assert.equal(await manager.locator('.rectification-timeline img').count() >= 3, true)
    await manager.getByRole('textbox', { name: '撤回原因' }).fill('误触闭环，恢复待确认')
    await manager.getByRole('button', { name: '撤回至待项目经理确认', exact: true }).click()
    await waitLog(manager, '误触闭环，恢复待确认')
    await manager.getByRole('button', { name: '关闭', exact: true }).click()
    assert.match(await metricValue('隐患总数'), /^1/)
    assert.match(await metricValue('已闭环问题'), /^0/)
    await manager.getByRole('tab', { name: /待处理隐患/ }).click()
    await manager.getByRole('button', { name: '查看并处理', exact: true }).first().waitFor()
    assert.deepEqual(errors, [])
    console.log('PASS: first save starts rectification; saved progress and review evidence submit without retyping; full rectification workflow; closure removes active hazards; reload preserves archived history; withdrawal restores active task; desktop/mobile layout; no page errors.')
  } finally {
    for (const context of contexts) await context.close()
    await browser.close()
  }
}
main().catch((error) => { console.error(error.message); process.exitCode = 1 })
