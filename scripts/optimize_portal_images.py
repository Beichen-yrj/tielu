"""Generate portal WebP renditions from the unchanged source JPGs (Pillow)."""
import hashlib
import json
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'public' / 'portal'
NAMES = [
    'hero-locomotive', 'hero-heavy-transport', 'hero-container-yard',
    'overview-terminal', 'showcase-container-loading',
    'news-tank-wagons', 'news-oil-tankers', 'news-chemical-tank',
    'news-rail-containers', 'news-tank-containers', 'news-terminal-crane',
]


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


manifest = []
for name in NAMES:
    source = ASSETS / f'{name}.jpg'
    with Image.open(source) as original:
        image = ImageOps.exif_transpose(original).convert('RGB')
        for width in (960, 1600) if name.startswith('hero-') else (640, 1280):
            output = ASSETS / f'{name}-{width}.webp'
            rendition = image.copy()
            rendition.thumbnail((width, round(image.height * width / image.width)), Image.Resampling.LANCZOS)
            rendition.save(output, 'WEBP', quality=82, method=6)
            manifest.append({
                'source': source.relative_to(ROOT).as_posix(),
                'source_sha256': sha256(source),
                'output': output.relative_to(ROOT).as_posix(),
                'output_sha256': sha256(output),
                'dimensions': list(rendition.size),
                'bytes': output.stat().st_size,
                'method': 'Pillow WebP quality=82, LANCZOS, no crop, RGB',
            })

(ROOT / 'scripts' / 'portal-image-manifest.json').write_text(
    json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8',
)
sizes = {Path(item['source']).name: item['dimensions'] for item in manifest if not Path(item['source']).name.startswith('hero-')}
(ROOT / 'src' / 'portalImageSizes.ts').write_text(
    '// Generated by scripts/optimize_portal_images.py; dimensions of the large rendition.\n'
    + 'export const portalImageSizes: Record<string, [number, number]> = '
    + json.dumps(sizes, indent=2) + '\n', encoding='utf-8',
)
print(f'Generated {len(manifest)} images, {sum(item["bytes"] for item in manifest):,} bytes')
