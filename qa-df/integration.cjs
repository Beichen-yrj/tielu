const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright')
async function main(){
 const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_EXECUTABLE||undefined,args:['--enable-webgl','--enable-unsafe-swiftshader']})
 const errors=[],checks=[]
 try{
  const page=await browser.newPage({viewport:{width:1560,height:950}})
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto('http://127.0.0.1:4175/')
  await page.getByRole('button',{name:'进入管理平台',exact:true}).first().click()
  await page.getByRole('button',{name:/后端未启动/}).click()
  await page.locator('.main-area h1').filter({hasText:'风险评估'}).waitFor()
  const search=page.locator('.hazard-toolbar input').first()
  await search.fill('巡检状态保留')
  await page.screenshot({path:path.join(__dirname,'results','platform-entry.png')})
  await page.locator('.simulation-switch').click()
  const frame=page.frames().find(f=>f.url().includes('digital-factory-3d.html'))||await (await page.locator('iframe').elementHandle()).contentFrame()
  await frame.waitForFunction(()=>window.DF)
  await page.waitForTimeout(1200)
  assert.equal(await page.locator('.simulation-workspace').isVisible(),true)
  await frame.locator('#film').click()
  await page.waitForFunction(()=>document.querySelector('.simulation-return').classList.contains('is-clean'))
  assert.equal(await page.locator('.simulation-return').evaluate(el=>getComputedStyle(el).opacity),'0')
  checks.push('embedded clean recording hides parent controls')
  await frame.locator('body').press('Escape')
  await frame.locator('#back').click()
  await page.locator('.simulation-workspace').waitFor({state:'detached'})
  assert.equal(await search.inputValue(),'巡检状态保留')
  checks.push('return link preserves original assessment page and search state')
  await page.locator('.simulation-switch').click()
  const frame2=await (await page.locator('iframe').elementHandle()).contentFrame()
  await frame2.waitForFunction(()=>window.DF)
  await page.getByRole('button',{name:'关闭仿真演示并返回原页面'}).click()
  assert.equal(await page.locator('.simulation-workspace').count(),0)
  assert.equal(await search.inputValue(),'巡检状态保留')
  checks.push('external close button unmounts WebGL frame and preserves original page')
  await page.setViewportSize({width:390,height:844})
  assert.equal(await page.locator('.simulation-switch').isVisible(),true)
  await page.locator('.simulation-switch').click()
  const mobile=await (await page.locator('iframe').elementHandle()).contentFrame()
  await mobile.waitForFunction(()=>window.DF)
  await page.waitForTimeout(1000)
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)
  await page.screenshot({path:path.join(__dirname,'results','platform-mobile.png')})
  checks.push('mobile switch and full viewport scene')
  assert.deepEqual(errors,[])
  const report={date:new Date().toISOString(),checks,errors}
  fs.writeFileSync(path.join(__dirname,'results','integration.json'),JSON.stringify(report,null,2));console.log(report)
 }finally{await browser.close()}
}
main().catch(e=>{console.error(e);process.exitCode=1})
