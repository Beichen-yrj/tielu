const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { pathToFileURL } = require('node:url')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const root = path.resolve(__dirname, '..')
const output = path.join(__dirname, 'results')
fs.mkdirSync(output, { recursive: true })
async function main() {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_EXECUTABLE || undefined, args: ['--enable-webgl', '--enable-unsafe-swiftshader'] })
  const errors = [], external = [], checks = []
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, offline: true })
    const page = await context.newPage()
    page.on('pageerror', e => errors.push(e.message))
    page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
    page.on('request', r => { if (/^https?:/.test(r.url())) external.push(r.url()) })
    const file = pathToFileURL(path.resolve(root, '../digital-factory-3d.html')).href
    await page.goto(file + '?lq=1&still=1')
    await page.waitForFunction(() => window.DF)
    await page.waitForTimeout(800)
    await page.screenshot({ path: path.join(output, 'overview.png') })
    assert.equal(await page.locator('#error').isHidden(), true)
    assert.equal(await page.locator('.zonebutton').count(), 6)
    checks.push('file:// loads with offline context, 6 zones, no external requests')
    const initialState = await page.evaluate(() => window.DF.state)
    assert.ok(initialState.drawCalls < 500, `draw calls ${initialState.drawCalls} < 500`)
    assert.ok(initialState.triangles < 1200000, 'triangle budget')
    for (let i = 0; i < 6; i++) {
      await page.locator('.zonebutton').nth(i).click()
      await page.waitForTimeout(1450)
      await page.screenshot({ path: path.join(output, `zone-${i + 1}.png`) })
      assert.equal(await page.locator('#inspector').isVisible(), true)
      assert.equal(await page.locator('#inspectname').textContent(), ['进场核验区','罐车装卸栈台','包装危货站台','到发与调车区','暂存交接区','应急保障区'][i])
    }
    await page.locator('#focusDevice').click()
    await page.waitForTimeout(1450)
    assert.equal(await page.locator('#inspectname').textContent(), '应急保障区')
    assert.equal(await page.locator('#viewcode').textContent(), 'Z06')
    checks.push('all six navigation views and station focus')
    await page.keyboard.press('d'); assert.equal(await page.evaluate(() => window.DF.state.showData), false)
    await page.keyboard.press('d'); await page.keyboard.press('l'); assert.equal(await page.evaluate(() => window.DF.state.showLabels), false)
    await page.keyboard.press('l'); await page.locator('#rate').click(); await page.locator('#rate').click()
    assert.equal(await page.evaluate(() => window.DF.SIM.rate), 4)
    await page.keyboard.press('0'); await page.waitForTimeout(1500)
    const before = await page.evaluate(() => window.DF.state.view)
    await page.mouse.move(700, 490); await page.mouse.wheel(0, -250)
    await page.waitForTimeout(100)
    assert.ok(await page.evaluate(d => window.DF.state.view.dist < d, before.dist))
    await page.mouse.move(700, 490); await page.mouse.down(); await page.mouse.move(780, 510, { steps: 12 }); await page.mouse.up()
    assert.ok(await page.evaluate(a => Math.abs(window.DF.state.view.azim - a) > .1, before.azim))
    checks.push('data, labels, rate, orbit and wheel controls')
    // Ray picking uses the same world/camera projection as a user click.
    const point = await page.evaluate(() => { const z=window.DF.zones[4]; const p=z.anchor.clone();p.y=4;p.project(window.DF.camera);return {x:(p.x*.5+.5)*innerWidth,y:(-p.y*.5+.5)*innerHeight} })
    await page.mouse.click(point.x, point.y)
    assert.equal(await page.locator('#inspector').isVisible(), true)
    checks.push('scene ray picking opens inspection')
    await page.keyboard.press('h');assert.equal(await page.evaluate(() => window.DF.state.hiddenUI), true);await page.keyboard.press('h')
    await page.locator('#film').click();assert.equal(await page.evaluate(() => window.DF.state.filmMode && window.DF.state.touring && window.DF.state.hiddenUI), true)
    await page.keyboard.press('Escape');assert.equal(await page.evaluate(() => window.DF.state.hiddenUI || window.DF.state.touring), false)
    checks.push('clean recording mode and Escape recovery')
    await page.goto(file + '?lq=1&tour=1&tourfast=1')
    await page.waitForFunction(() => window.DF)
    const timeBefore = await page.locator('#clock').textContent()
    await page.waitForFunction(() => window.DF.state.coverage.length === 9, { timeout: 30000 })
    await page.waitForFunction(() => window.DF.state.tourElapsed > 14.4 && window.DF.state.chapter === 0, { timeout: 10000 })
    assert.notEqual(await page.locator('#clock').textContent(), timeBefore)
    const performance = await page.evaluate(() => ({ state: window.DF.state, vendor: window.DF.renderer.getContext().getParameter(window.DF.renderer.getContext().RENDERER) }))
    checks.push('nine tour chapters in order, loop returns to overview, simulation clock advances')
    await page.screenshot({ path: path.join(output, 'tour-loop.png') })
    await page.goto(file + '?lq=1&still=1&hideui=1')
    await page.waitForFunction(() => window.DF)
    await page.waitForTimeout(800)
    await page.screenshot({ path: path.join(output, 'stable-a.png') })
    await page.waitForTimeout(350)
    await page.screenshot({ path: path.join(output, 'stable-b.png') })
    // A portrait viewport must not cause horizontal document overflow.
    await page.setViewportSize({width:390,height:844})
    await page.goto(file + '?lq=1&still=1')
    await page.waitForFunction(() => window.DF)
    await page.waitForTimeout(800)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.screenshot({ path: path.join(output, 'mobile.png') })
    await page.keyboard.press('3');await page.waitForTimeout(1500)
    assert.equal(await page.locator('#inspector').isVisible(),true)
    checks.push('390 × 844 viewport and inspection layout')
    await page.setViewportSize({width:1440,height:900})
    await page.goto(file + '?still=1')
    await page.waitForFunction(() => window.DF)
    await page.waitForTimeout(2500)
    await page.screenshot({path:path.join(output,'overview-quality.png')})
    const quality = await page.evaluate(() => ({state:window.DF.state,dpr:window.DF.renderer.getPixelRatio(),shadows:window.DF.renderer.shadowMap.enabled}))
    await page.keyboard.press('h')
    await page.waitForTimeout(450)
    await page.screenshot({path:path.join(output,'quality-stable-a.png')})
    await page.waitForTimeout(350)
    await page.screenshot({path:path.join(output,'quality-stable-b.png')})
    checks.push('default quality with native canvas antialiasing, soft shadows, local studio environment')
    assert.deepEqual(external, [])
    assert.deepEqual(errors, [])
    fs.writeFileSync(path.join(output, 'report.json'), JSON.stringify({ date: new Date().toISOString(), checks, errors, external, initialState, performance, quality }, null, 2))
    console.log(JSON.stringify({ checks, errors, external, performance, quality }, null, 2))
  } finally { await browser.close() }
}
main().catch(e => { console.error(e); process.exitCode = 1 })
